def _resolve_rtk_binary() -> str | None:
    """Find the pinned RTK binary.

    Order:
      1. ``$COCKPIT_RTK_BIN`` env override (operator ad-hoc testing).
      2. The cache directory at :data:`RTK_CACHE_ROOT`.
      3. ``shutil.which("rtk")`` (PATH lookup).

    Returns the absolute path or ``None``. Never raises — a path that
    fails the version check is treated as "not found".
    """
    override = os.environ.get("COCKPIT_RTK_BIN")
    if override and Path(override).is_file():
        return override

    cached = _resolve_cache_binary()
    if cached is not None:
        return cached

    return shutil.which("rtk")


def _resolve_cache_binary() -> str | None:
    """Return the cached pinned binary or ``None`` if not present."""
    p = RTK_CACHE_ROOT / RTK_PINNED_VERSION / "bin" / "rtk"
    return str(p) if p.is_file() else None


def _verify_rtk_version(binary: str) -> tuple[bool, str]:
    """Run ``<binary> --version`` and check the first token starts with
    the pinned version. Returns ``(ok, version)``.

    Anything other than ``"0.43.0[.x]"`` → ``ok=False``. This is the
    "no silent fallback" contract: a too-old binary on PATH must not
    look like a working install.
    """
    import subprocess
    try:
        out = subprocess.run(
            [binary, "--version"], capture_output=True, text=True,
            timeout=5, check=False,
        )
    except (OSError, subprocess.TimeoutExpired) as exc:
        return (False, f"unreachable: {type(exc).__name__}")
    text = (out.stdout or out.stderr or "").strip()
    # The pinned binary prints "rtk 0.43.0" — first token after `rtk `.
    parts = text.split()
    version = parts[1] if len(parts) >= 2 and parts[0] == "rtk" else text
    if version.startswith(RTK_PINNED_VERSION + ".") or version == RTK_PINNED_VERSION:
        return (True, version)
    return (False, version or "unknown")


def _ensure_cache_ready() -> None:
    """Best-effort cache bootstrap. No-op when the cache already has the
    pinned binary; otherwise tries one sync download from
    ``rtk-ai/rtk@v<RTK_PINNED_VERSION>`` with a 5s timeout. Never raises.

    Out-of-band bootstrap via ``scripts/install-rtk.sh`` (a follow-up
    card) is the air-gap path; this helper is for the connected case.
    """
    if _resolve_cache_binary() is not None:
        return  # cache hit — nothing to do

    cache_dir = RTK_CACHE_ROOT / RTK_PINNED_VERSION
    bin_dir = cache_dir / "bin"
    hooks_dir = cache_dir / "hooks"
    bin_dir.mkdir(parents=True, exist_ok=True)
    hooks_dir.mkdir(parents=True, exist_ok=True)

    import subprocess
    base = (
        f"https://raw.githubusercontent.com/rtk-ai/rtk/"
        f"v{RTK_PINNED_VERSION}"
    )
    for relpath, dest in (
        ("hooks/claude/rtk-rewrite.sh", hooks_dir / "rtk-rewrite.sh"),
    ):
        if dest.is_file():
            continue
        try:
            subprocess.run(
                ["curl", "-fsSL", "--max-time", "5", f"{base}/{relpath}",
                 "-o", str(dest)],
                check=True, capture_output=True, timeout=10,
            )
            _make_executable(dest)
        except (OSError, subprocess.SubprocessError, subprocess.TimeoutExpired):
            return  # best-effort; do not raise
