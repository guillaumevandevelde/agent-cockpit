"""Worktree-local RTK (token-saver) installer.

Opt-in, fail-open, board kill-switchable. The helper is the dispatcher-side
seam of kaart ``c31333bf…`` and
``docs/superpowers/specs/2026-07-24-token-saver-integration-design.md``.

Public surface:

- :func:`maybe_install` — dispatcher-facing entry point. Never raises.
  Returns ``(status, reason)`` where ``status`` is one of
  ``"active" | "inactive" | "failed"``.
- :func:`is_board_enabled` / :func:`set_board_enabled` — the per-project
  runtime kill-switch, backed by ``KanbanMeta``.
- :func:`post_note` — activity-feed comment with 60s dedup so a backlog
  flush does not flood the feed with one ``Token saver …`` note per
  card.
- :func:`write_rtk_settings_into_worktree` — the filesystem step in
  isolation, exposed for the measurement harness so the harness exercises
  the *exact* same JSON-merge code path the dispatcher does.

Fail-open contract: every step wraps a guarded try/except and degrades
to ``("failed", "<reason>")`` rather than re-raising. The dispatcher
catches ``(status, reason)`` and continues the spawn unchanged.
"""
from __future__ import annotations

import json
import os
import shutil
import stat
import tempfile
from datetime import UTC, datetime
from pathlib import Path
from typing import Any

from sqlalchemy import select

from app.kanban.models import KanbanColumn, KanbanMeta, KanbanOp

# Pinned RTK release. Single source of truth — bump here when the project
# decides to upgrade. Mirrors docs/cockpit/token-saver-mechanismen-decision.md §8
# (versie-pinnen verplicht; het project shipt RC's in een tempo dat
# auto-update onverantwoord maakt).
RTK_PINNED_VERSION = "0.43.0"

# Cache layout — per-user (under $HOME), per-version. Layout under this
# directory:
#   bin/rtk               — pinned RTK binary, executable
#   hooks/rtk-rewrite.sh  — pinned upstream rewrite hook, read-only after install
RTK_CACHE_ROOT = Path(
    os.environ.get(
        "COCKPIT_RTK_CACHE_ROOT",
        f"{os.environ.get('HOME', '/root')}/.local/share/cockpit/rtk",
    )
)

# Default dedup window for the activity-feed ``**Note:** Token saver …``
# comment. Sized so a backlog flush running multiple cards within seconds
# collapses to one note per dispatch tick, not one per card. Tests can
# monkeypatch this to 0 to verify the dedup branch deterministically.
_DEDUP_WINDOW_SECONDS = 60

# Activity-feed prefix. Deliberately distinct from every other consumer
# prefix in docs/cockpit/kanban-conventions.md §2 (``**Summary:**`` /
# ``**Impediment:**`` / ``**Resolution:**`` / ``**Revisit:**`` /
# ``**Review requested:**``). Operator grep for ``Token saver`` lands on
# exactly these comments.
_NOTE_PREFIX = "**Note:** Token saver"

# Wrapper hook script body — small enough to inline so the worktree
# bootstrap is one filesystem write. Responsibilities:
#   1. Bypass ``git diff`` rewriting (lossy on shipping lanes; see
#      docs/cockpit/token-saver-mechanismen-decision.md §4.1.3).
#   2. Bypass bare ``grep`` without ``-r`` (host ``grep`` is ugrep which
#      recurses; RTK invokes GNU grep which fails on directory args —
#      see §4.1.4).
#   3. Delegate the rewrite to the pinned upstream script.
#   4. Exit 0 on any failure (Claude Code requirement for PreToolUse).
_HOOK_SCRIPT_BODY = f"""#!/usr/bin/env bash
# Auto-generated by Cockpit token-saver integration (kaart c31333bf…).
# Do not edit by hand — re-running `maybe_install` regenerates this file.
# Source: hooks/claude/rtk-rewrite.sh from rtk-ai/rtk v{RTK_PINNED_VERSION}.
set -e
INPUT="$(cat)"
CMD="$(printf '%s' "$INPUT" | jq -r '.tool_input.command // empty' 2>/dev/null || true)"
if [ -z "$CMD" ]; then exit 0; fi
# Bypass: bare `grep` without -r/--recursive on directory args.
# (RTK's grep rewriter shells to GNU grep, which dies on a directory
# arg; this host's grep is ugrep, which silently recurses. Bypassing
# the rewrite preserves the host's behaviour.)
case "$CMD" in
  grep*)
    if echo "$CMD" | grep -Eq -- ' (-r|-R|--recursive)( |$)'; then
      : # recursion flag present — let RTK handle it
    else
      exit 0
    fi
    ;;
esac
# Bypass: `git diff` (lossy on shipping lanes — see decision doc §4.1.3).
case "$CMD" in
  'git diff'*|'git' 'diff'*|*"git diff"*)
    exit 0
    ;;
esac
# Delegate to the pinned upstream rewrite script.
SCRIPT_DIR="$(cd "$(dirname "$0")" && pwd)"
exec "$SCRIPT_DIR/rtk-rewrite.sh" <<<"$INPUT"
"""


