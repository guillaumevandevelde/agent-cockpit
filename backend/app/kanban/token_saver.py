async def is_board_enabled(session, project_key: str) -> bool:
    """Whether the per-project runtime kill-switch is on.

    Reads the ``token_saver:<project_key>`` row from ``KanbanMeta`` and
    treats only the literal string ``"1"`` as on. Anything else
    (``"0"``, absent row, ``"yes"``, …) → ``False``. The dispatch hot
    path calls this on every tick so a flipped switch takes effect on
    the next dispatch without a backend restart.
    """
    if not project_key:
        return False
    row = (await session.execute(
        select(KanbanMeta).where(KanbanMeta.key == f"token_saver:{project_key}")
    )).scalar_one_or_none()
    return bool(row and row.value == "1")


async def set_board_enabled(session, project_key: str, enabled: bool) -> None:
    """Persist the per-project runtime kill-switch.

    Idempotent. Writes ``"1"`` or ``"0"`` matching the convention used
    by ``set_autodispatch`` / ``set_skip_permissions``: read the row,
    update value or insert. The KanbanMeta table is device-local (not
    op-log-backed), so no audit comment is posted — operators flip the
    toggle in the UI, not via dispatch.
    """
    key = f"token_saver:{project_key}"
    row = await session.get(KanbanMeta, key)
    if row is None:
        row = KanbanMeta(key=key, value="1" if enabled else "0")
        session.add(row)
    else:
        row.value = "1" if enabled else "0"
    await session.flush()


async def post_note(session, card_id: str, text: str) -> None:
    """Post a ``**Note:** Token saver …`` audit comment to a card's op-log.

    Dedup: if the most recent matching comment on this card landed
    within :data:`_DEDUP_WINDOW_SECONDS`, the new comment is suppressed.
    The dedup is per-card and per-prefix so a separate state-change on
    the same card (e.g. dispatch failure) is never silenced.
    """
    from app.kanban.operations import apply_operation

    full_text = f"{_NOTE_PREFIX}{text[len(_NOTE_PREFIX):] if text.startswith(_NOTE_PREFIX) else ': ' + text}"
    # Normalise: callers pass the *reason*; we always prepend the canonical
    # prefix. The dedup scan matches on the prefix so a re-post within the
    # window collapses to nothing.
    if not text.startswith(_NOTE_PREFIX):
        full_text = f"{_NOTE_PREFIX}: {text}"

    last = (await session.execute(
        select(KanbanOp)
        .where(KanbanOp.entity_id == card_id)
        .where(KanbanOp.op_type == "comment")
        .order_by(KanbanOp.hlc.desc())
        .limit(20)  # narrow scan; op-log has all history but we only need the tail
    )).scalars().all()

    now = datetime.now(UTC)
    for op in last:
        payload_text = (op.payload or {}).get("text", "")
        if not payload_text.startswith(_NOTE_PREFIX):
            continue
        try:
            # SQLite strips tzinfo; reattach UTC before subtracting.
            created = op.created_at
            if created.tzinfo is None:
                created = created.replace(tzinfo=UTC)
            age = (now - created).total_seconds()
        except Exception:
            continue
        if age < _DEDUP_WINDOW_SECONDS:
            return  # suppressed — within the dedup window

    await apply_operation(
        session, op_type="comment", entity_type="comment",
        project_key="", entity_id=card_id,
        payload={"text": full_text},
    )


async def maybe_install(
    session, *,
    card_id: str,
    project_key: str,
    column_name: str,
    worktree_path: str,
    repo_path: str,
) -> tuple[str, str]:
    """Decide whether to install RTK for this dispatch, and do it.

    Returns ``(status, reason)`` where ``status`` is one of:

    - ``"active"`` — wrapper hook + settings.json patched; spawn should
      carry ``RTK_TELEMETRY=off``.
    - ``"inactive"`` — per-lane flag or kill-switch off; no filesystem
      writes.
    - ``"failed"`` — attempted but couldn't install (RTK missing, wrong
      version, settings unwriteable, etc.); dispatch continues unchanged.

    Never raises. The dispatcher relies on this guarantee: a buggy
    helper must not crash the spawn hot path.
    """
    try:
        return await _maybe_install_impl(
            session, card_id=card_id, project_key=project_key,
            column_name=column_name,
            worktree_path=worktree_path, repo_path=repo_path,
        )
    except Exception as exc:  # pragma: no cover — defensive
        return ("failed", f"{type(exc).__name__}: {exc}")


async def _maybe_install_impl(
    session, *,
    card_id: str,
    project_key: str,
    column_name: str,
    worktree_path: str,
    repo_path: str,
) -> tuple[str, str]:
    # Per-lane opt-in.
    col = (await session.execute(
        select(KanbanColumn).where(
            KanbanColumn.project_key == project_key,
            KanbanColumn.name == column_name,
        )
    )).scalar_one_or_none()
    if col is None or not getattr(col, "token_saver_enabled", 0):
        return ("inactive", "per-lane flag off")

    # Board kill-switch.
    if not await is_board_enabled(session, project_key):
        return ("inactive", "board kill-switch off")

    # Worktree exists.
    wt = Path(worktree_path)
    if not wt.is_dir():
        return ("failed", f"worktree not found: {worktree_path}")

    # Locate RTK.
    binary = _resolve_rtk_binary()
    if binary is None:
        return ("failed", "rtk binary missing")

    # Verify version.
    ok, version = _verify_rtk_version(binary)
    if not ok:
        return ("failed", f"rtk version {version} (need >= {RTK_PINNED_VERSION})")

    # Best-effort cache bootstrap (idempotent; no-op on a fully-cached box).
    try:
        _ensure_cache_ready()
    except Exception:
        pass  # already fail-open at every step

    # Write the wrapper hook + patch settings.json.
    write_rtk_settings_into_worktree(str(wt), binary)
    return ("active", f"RTK {RTK_PINNED_VERSION}")


